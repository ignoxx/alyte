import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import process from 'node:process';

const root = resolve(new URL('..', import.meta.url).pathname);
const sourcePath = resolve(
  root,
  'apps/mobile/modules/alyte-local-models/grammar/semantic-mapper-v1.gbnf',
);
const swiftPath = resolve(
  root,
  'apps/mobile/modules/alyte-local-models/ios/AlyteSemanticMapperGrammar.generated.swift',
);
const typescriptPath = resolve(
  root,
  'apps/mobile/src/features/local-models/semantic-mapper-grammar.generated.ts',
);
const grammar = readFileSync(sourcePath, 'utf8').trimEnd();

const swift = `// @generated by scripts/generate-semantic-mapper-grammar.mjs; do not edit.
enum AlyteSemanticMapperGrammar {
  static let root = #"""
${grammar}
"""#
}
`;
const typescript = `// @generated by scripts/generate-semantic-mapper-grammar.mjs; do not edit.
export const ALYTE_SEMANTIC_MAPPER_GRAMMAR = ${JSON.stringify(grammar)} as const;
`;
const formattedTypescript = execFileSync(
  process.execPath,
  [resolve(root, 'node_modules/prettier/bin/prettier.cjs'), '--parser', 'typescript'],
  { input: typescript, encoding: 'utf8' },
);

function writeOrCheck(path, content) {
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== content) {
      process.stderr.write(`Semantic mapper grammar output drift: ${path}\n`);
      process.exitCode = 1;
    }
  } else {
    writeFileSync(path, content);
  }
}

writeOrCheck(swiftPath, swift);
writeOrCheck(typescriptPath, formattedTypescript);
