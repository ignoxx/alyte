import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import process from 'node:process';

const root = resolve(new URL('..', import.meta.url).pathname);
const grammarTargets = [
  {
    source: 'apps/mobile/modules/alyte-local-models/grammar/semantic-mapper-v1.gbnf',
    swift: 'apps/mobile/modules/alyte-local-models/ios/AlyteSemanticMapperGrammar.generated.swift',
    typescript: 'apps/mobile/src/features/local-models/semantic-mapper-grammar.generated.ts',
    swiftType: 'AlyteSemanticMapperGrammar',
    typescriptName: 'ALYTE_SEMANTIC_MAPPER_GRAMMAR',
  },
  {
    source: 'apps/mobile/modules/alyte-local-models/grammar/geometry-variant-selector-v2.gbnf',
    swift:
      'apps/mobile/modules/alyte-local-models/ios/AlyteGeometryVariantSelectorGrammar.generated.swift',
    typescript:
      'apps/mobile/src/features/local-models/geometry-variant-selector-grammar.generated.ts',
    swiftType: 'AlyteGeometryVariantSelectorGrammar',
    typescriptName: 'ALYTE_GEOMETRY_VARIANT_SELECTOR_GRAMMAR',
  },
];

function writeOrCheck(path, content, label) {
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== content) {
      process.stderr.write(`${label} grammar output drift: ${path}\n`);
      process.exitCode = 1;
    }
  } else {
    writeFileSync(path, content);
  }
}

for (const target of grammarTargets) {
  const grammar = readFileSync(resolve(root, target.source), 'utf8').trimEnd();
  const swift = `// @generated by scripts/generate-semantic-mapper-grammar.mjs; do not edit.
enum ${target.swiftType} {
  static let root = #"""
${grammar}
"""#
}
`;
  const typescript = `// @generated by scripts/generate-semantic-mapper-grammar.mjs; do not edit.
export const ${target.typescriptName} = ${JSON.stringify(grammar)} as const;
`;
  const formattedTypescript = execFileSync(
    process.execPath,
    [resolve(root, 'node_modules/prettier/bin/prettier.cjs'), '--parser', 'typescript'],
    { input: typescript, encoding: 'utf8' },
  );
  writeOrCheck(resolve(root, target.swift), swift, target.swiftType);
  writeOrCheck(resolve(root, target.typescript), formattedTypescript, target.typescriptName);
}
