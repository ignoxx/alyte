import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import process from 'node:process';

const root = resolve(new URL('..', import.meta.url).pathname);
const sourcePath = resolve(root, 'apps/mobile/modules/alyte-local-models/manifest/production.json');
const swiftPath = resolve(
  root,
  'apps/mobile/modules/alyte-local-models/ios/AlyteLocalModelManifest.swift',
);
const typescriptPath = resolve(
  root,
  'apps/mobile/src/features/local-models/production-manifest.generated.ts',
);
const manifest = JSON.parse(readFileSync(sourcePath, 'utf8'));

const swiftString = (value) => JSON.stringify(value);
const swiftArray = (values) => `[${values.map(swiftString).join(', ')}]`;
const swift = `// @generated by scripts/generate-local-model-manifest.mjs; do not edit.
import Foundation

enum AlyteLocalModelManifest {
  static let version = ${swiftString(manifest.manifestVersion)}
  static let packID = ${swiftString(manifest.pack.id)}
  static let sourceRepository = ${swiftString(manifest.pack.source.repository)}
  static let sourceRevision = ${swiftString(manifest.pack.source.revision)}
  static let artifactRepository = ${swiftString(manifest.pack.artifact.repository)}
  static let artifactRevision = ${swiftString(manifest.pack.artifact.revision)}
  static let filename = ${swiftString(manifest.pack.artifact.filename)}
  static let artifactURL = ${swiftString(manifest.pack.artifact.url)}
  static let bytes: Int64 = ${manifest.pack.artifact.bytes.toLocaleString('en-US').replaceAll(',', '_')}
  static let sha256 = ${swiftString(manifest.pack.artifact.sha256)}
  static let publisher = ${swiftString(manifest.pack.publisher)}
  static let license = ${swiftString(manifest.pack.license)}
  static let format = ${swiftString(manifest.pack.format)}
  static let quantization = ${swiftString(manifest.pack.quantization)}
  static let runtimeID = ${swiftString(manifest.runtime.id)}
  static let runtimeRepository = ${swiftString(manifest.runtime.repository)}
  static let runtimeRevision = ${swiftString(manifest.runtime.revision)}
  static let promptBundle = ${swiftString(manifest.compatibility.promptBundle)}
  static let ocrChunk = ${swiftString(manifest.compatibility.ocrChunk)}
  static let semanticSchema = ${swiftString(manifest.compatibility.semanticSchema)}
  static let languages = ${swiftArray(manifest.compatibility.languages)}
  static let minimumIOS = ${swiftString(manifest.requirements.minimumIOS)}
  static let minimumFreeBytes: Int64 = ${manifest.requirements.minimumFreeBytes.toLocaleString('en-US').replaceAll(',', '_')}
  static let minimumMemoryBytes: Int64 = ${manifest.requirements.minimumMemoryBytes.toLocaleString('en-US').replaceAll(',', '_')}
  static let allowedHosts = ${swiftArray(manifest.allowlist.hosts)}

  static var expectedURL: URL { URL(string: artifactURL)! }

  static func publicManifest() -> [String: Any] {
    [
      "manifestVersion": version,
      "pack": [
        "id": packID,
        "source": ["repository": sourceRepository, "revision": sourceRevision],
        "artifact": [
          "repository": artifactRepository,
          "revision": artifactRevision,
          "filename": filename,
          "url": artifactURL,
          "bytes": bytes,
          "sha256": sha256,
        ],
        "publisher": publisher,
        "license": license,
        "format": format,
        "quantization": quantization,
      ],
      "runtime": ["id": runtimeID, "repository": runtimeRepository, "revision": runtimeRevision],
      "compatibility": [
        "languages": languages,
        "promptBundle": promptBundle,
        "ocrChunk": ocrChunk,
        "semanticSchema": semanticSchema,
      ],
      "requirements": [
        "minimumIOS": minimumIOS,
        "minimumFreeBytes": minimumFreeBytes,
        "minimumMemoryBytes": minimumMemoryBytes,
      ],
      "allowlist": ["hosts": allowedHosts, "files": [filename]],
    ]
  }

  static func isAllowedRedirect(_ url: URL) -> Bool {
    guard url.scheme?.lowercased() == "https", let host = url.host?.lowercased(), allowedHosts.contains(host),
          url.user == nil, url.password == nil else { return false }
    return true
  }
}
`;

const typescript = `// @generated by scripts/generate-local-model-manifest.mjs; do not edit.
export const productionLocalModelManifest = Object.freeze(${JSON.stringify(manifest, null, 2)} as const);
`;
const formattedTypescript = execFileSync(
  process.execPath,
  [resolve(root, 'node_modules/prettier/bin/prettier.cjs'), '--parser', 'typescript'],
  { input: typescript, encoding: 'utf8' },
);

function writeOrCheck(path, content) {
  if (process.argv.includes('--check')) {
    const current = readFileSync(path, 'utf8');
    if (current !== content) {
      process.stderr.write(`Manifest output drift: ${path}\n`);
      process.exitCode = 1;
    }
  } else {
    writeFileSync(path, content);
  }
}

writeOrCheck(swiftPath, swift);
writeOrCheck(typescriptPath, formattedTypescript);
